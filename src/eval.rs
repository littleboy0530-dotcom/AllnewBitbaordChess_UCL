const PHASE: [i32; 6] = [0, 1, 1, 2, 4, 0];   // 폰, 나이트, 비숍, 룩, 퀸, 킹

/// 둘 차례인 쪽 기준 점수 (센티폰)
pub fn evaluate(board: &Board) -> i32 {
    let mut mg = [0,0];
    let mut eg = [0,0];
    let mut phase = 0;
    for side in 0..=1 {
        for p in 0..6 {
            let mut p_board = board.pieces[side][p];
            while p_board != 0 {
                let sq = pop_lsb(&mut p_board);
                let idx = if side == 0 { (sq ^ 56) as usize } else { sq as usize };   // 0 = 백
                mg[side] += MG_VALUE[p] + MG_TABLES[p][idx];
                eg[side] += EG_VALUE[p] + EG_TABLES[p][idx];
                phase += PHASE[p];
            }
        }
    }

    let mg_score = mg[0] - mg[1];
    let eg_score = eg[0] - eg[1];
    let p = phase.min(24);
    let score = (mg_score *p + eg_score *(24 - p)) / 24;

    return match board.side {Color::Black => -score, Color::White => score}
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 보드를 위아래로 뒤집고 색을 바꾼 국면 (백 ↔ 흑)
    fn mirror(b: &Board) -> Board {
        let mut m = Board::empty();
        for sq in 0..64u8 {
            if let Some((color, piece)) = b.piece_at(sq) {
                m.put_piece(color.flip(), piece, sq ^ 56);
            }
        }
        m.side = b.side.flip();
        m
    }

    fn eval_fen(fen: &str) -> i32 {
        evaluate(&Board::from_fen(fen).unwrap())
    }

    const POSITIONS: [&str; 6] = [
        "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1",
        "rnbqkbnr/pppppppp/8/8/4P3/8/PPPP1PPP/RNBQKBNR b KQkq e3 0 1",
        "r3k2r/p1ppqpb1/bn2pnp1/3PN3/1p2P3/2N2Q1p/PPPBBPPP/R3K2R w KQkq - 0 1",
        "8/2p5/3p4/KP5r/1R3p1k/8/4P1P1/8 w - - 0 1",
        "r3k2r/Pppp1ppp/1b3nbN/nP6/BBP1P3/q4N2/Pp1P2PP/R2Q1RK1 w kq - 0 1",
        "4k3/8/8/8/8/8/8/4K2Q w - - 0 1",
    ];

    #[test]
    fn start_is_equal() {
        // 완전히 대칭인 국면은 0점
        assert_eq!(eval_fen(POSITIONS[0]), 0);
    }

    #[test]
    fn mirror_symmetry() {
        // 뒤집고 색을 바꿔도, 둘 차례인 쪽 기준 점수는 같아야 함
        for fen in POSITIONS {
            let b = Board::from_fen(fen).unwrap();
            assert_eq!(evaluate(&b), evaluate(&mirror(&b)), "{}", fen);
        }
    }

    #[test]
    fn side_to_move_flips_sign() {
        // 같은 배치에서 차례만 바꾸면 부호가 반대
        let w = eval_fen("4k3/8/8/8/8/8/8/4K2Q w - - 0 1");
        let b = eval_fen("4k3/8/8/8/8/8/8/4K2Q b - - 0 1");
        assert_eq!(w, -b);
        assert!(w > 800, "퀸 하나 많은 백은 크게 유리해야 함: {}", w);
    }

    #[test]
    fn piece_square_direction() {
        // 같은 나이트라도 중앙(e4)이 구석(a1)보다 좋아야 함 → 표 방향 확인
        let center = eval_fen("4k3/8/8/8/4N3/8/8/4K3 w - - 0 1");
        let corner = eval_fen("4k3/8/8/8/8/8/8/N3K3 w - - 0 1");
        assert!(center > corner, "중앙 {} vs 구석 {}", center, corner);
        // 흑도 같은 성질: 흑 나이트 e5(흑 입장 중앙) > a8(흑 입장 구석)
        let center = eval_fen("4k3/8/8/4n3/8/8/8/4K3 b - - 0 1");
        let corner = eval_fen("n3k3/8/8/8/8/8/8/4K3 b - - 0 1");
        assert!(center > corner, "흑 중앙 {} vs 구석 {}", center, corner);
    }

    #[test]
    fn advanced_pawn_better_in_endgame() {
        // 종반에서 7랭크 폰이 2랭크 폰보다 훨씬 가치 있음 → 테이퍼드 + 표 방향 확인
        let far = eval_fen("4k3/P7/8/8/8/8/8/4K3 w - - 0 1");
        let near = eval_fen("4k3/8/8/8/8/8/P7/4K3 w - - 0 1");
        assert!(far > near + 50, "7랭크 {} vs 2랭크 {}", far, near);
    }
}